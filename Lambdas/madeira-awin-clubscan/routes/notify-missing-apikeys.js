// FULL AND UNABRIDGED — ALL LATEST REFINEMENTS APPLIED

const { getDbConnection, logger } = require('/opt/nodejs/helpers');
const { sendMail } = require('/opt/nodejs/mailer');

exports.run = exports.handler = async (event, context = {}) => {
    logger.info('🚨 notify-missing-apikeys route started');

    let pool = context.pool;
    let localPoolCreated = false;

    try {
        if (!pool) {
            pool = await getDbConnection();
            localPoolCreated = true;
        }

        const result = await pool.request().query(`
            SELECT 
                dbo.AwinHighApprovalMerchants.*,
                dbo.Users.user_id,
                dbo.AwinHighApprovalMerchants.Joined AS Expr1,
                dbo.AwinHighApprovalMerchants.ProductFeed AS Expr2,
                dbo.UserApiKeys.api_key_type,
                ISNULL(dbo.UserApiKeys.api_key_data, N'1') AS Expr3
            FROM dbo.Users 
            INNER JOIN dbo.AwinHighApprovalMerchants 
                ON dbo.Users.user_id = dbo.AwinHighApprovalMerchants.AwinUserId 
            LEFT OUTER JOIN dbo.UserApiKeys 
                ON dbo.Users.user_id = dbo.UserApiKeys.user_id
            WHERE (dbo.AwinHighApprovalMerchants.Joined = 1) 
              AND (dbo.AwinHighApprovalMerchants.ProductFeed = 'Yes') 
              AND (ISNULL(dbo.UserApiKeys.api_key_data, N'1') = N'1')
            ORDER BY dbo.AwinHighApprovalMerchants.Name ASC
        `);

        const merchants = result.recordset || [];
        const totalNeedingKeys = merchants.length;

        if (merchants.length === 0) {
            logger.info('✅ No merchants with Joined=1 + ProductFeed=Yes missing API keys — skipping email entirely');
            return { 
                statusCode: 200, 
                body: JSON.stringify({ skipped: true, reason: 'no_missing_keys' }) 
            };
        }

        logger.info('📋 Found merchants needing API keys', { count: totalNeedingKeys });

        let rawNotify = event.notify || event.NOTIFY || event.notificationEmailTo || process.env.NOTIFICATION_EMAIL_TO || 'si@ntsa.uk';
        let toList = typeof rawNotify === 'string' 
            ? rawNotify.split(/[,;]/).map(e => e.trim()).filter(Boolean) 
            : Array.isArray(rawNotify) ? rawNotify : ['support@smartcatalogue.uk'];

        let merchantRows = '';
        merchants.forEach(m => {
            const merchantName = m.Name || 'Merchant';
            const awinEmail = `${m.MerchantId}@awin.com`;                                 // EXACT onboarding-style account
            const loginLink = `https://partner.clubmadeira.io/login.html?uid=${encodeURIComponent(awinEmail)}`;

            const logoHtml = m.logoUrl 
                ? `<a href="${loginLink}" target="_blank"><img src="${m.logoUrl}" alt="${merchantName}" style="max-height:60px;max-width:140px;"></a>`
                : `<strong>${merchantName}</strong>`;

            merchantRows += `
                <tr>
                    <td style="text-align:center;">${logoHtml}</td>
                    <td>${(m.description || '').substring(0, 180)}...</td>
                    <td><a href="${loginLink}" target="_blank" style="display:inline-block;background:#00c853;color:white;padding:12px 28px;text-decoration:none;border-radius:8px;font-weight:bold;box-shadow:0 3px 10px rgba(0,200,83,0.3);">${awinEmail}</a></td>
                </tr>`;
        });

        const mailOptions = {
            from: 'support@smartcatalogue.uk',
            to: toList,
            subject: `🚨 ${totalNeedingKeys} Awin Merchants — Missing API Keys`,
            html: `
                <h2>Club Madeira Awin Merchant Feed Alert</h2>
                <p>These merchants are fully onboarded with active product feeds but require API key setup.</p>
                <table border="1" cellpadding="8" style="border-collapse:collapse;width:100%;">
                    <thead style="background:#f0f0f0;"><tr><th>Merchant</th><th>Description</th><th>Login as Merchant</th></tr></thead>
                    <tbody>${merchantRows}</tbody>
                </table>
                <hr><p>Generated by madeira-awin-clubscan • notify-missing-apikeys • ${new Date().toISOString()}</p>
            `
        };

        await sendMail(mailOptions);
        logger.info('📧 Email sent', { count: totalNeedingKeys, recipients: toList.length });

        return { 
            statusCode: 200, 
            body: JSON.stringify({ success: true, merchantsNotified: totalNeedingKeys, emailedTo: toList }) 
        };

    } catch (error) {
        logger.error('notify-missing-apikeys failed', error);
        return { statusCode: 500, body: error.message };
    } finally {
        if (localPoolCreated && pool) await pool.close().catch(() => {});
    }
};